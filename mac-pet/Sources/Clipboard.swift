// Кот запоминает последние скопированные тексты, и их можно вставить снова:
// из меню 🐱 или по сочетанию ⌃⌥V в любой программе.
// История живёт только в памяти и пропадает при выходе. Пароли из менеджеров
// паролей не запоминаются — они помечают их специальным типом в буфере обмена.

import AppKit
import Carbon

extension Notification.Name {
    static let murkaClipboardHotKey = Notification.Name("murkaClipboardHotKey")
}

@MainActor
final class ClipboardHistory {
    static let maxItems = 10
    static let maxLength = 20_000
    // Типы, которыми менеджеры паролей и другие программы помечают секретное и временное
    static let skippedTypes: [NSPasteboard.PasteboardType] = [
        NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType"),
        NSPasteboard.PasteboardType("org.nspasteboard.TransientType"),
        NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"),
        NSPasteboard.PasteboardType("com.agilebits.onepassword"),
    ]

    var items: [String] = []
    var lastChange = NSPasteboard.general.changeCount
    var enabled: Bool = UserDefaults.standard.object(forKey: "clipboardHistory") as? Bool ?? true {
        didSet {
            UserDefaults.standard.set(enabled, forKey: "clipboardHistory")
            if !enabled { items.removeAll() }
        }
    }
    var hotKey: EventHotKeyRef?

    // Возвращает только что скопированный текст, если он новый
    func poll() -> String? {
        let pb = NSPasteboard.general
        guard pb.changeCount != lastChange else { return nil }
        lastChange = pb.changeCount
        guard enabled else { return nil }
        let types = pb.types ?? []
        if types.contains(where: { Self.skippedTypes.contains($0) }) { return nil }
        guard let text = pb.string(forType: .string),
              !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty
        else { return nil }
        let clipped = String(text.prefix(Self.maxLength))
        remember(clipped)
        return clipped
    }

    func remember(_ text: String) {
        items.removeAll { $0 == text }
        items.insert(text, at: 0)
        if items.count > Self.maxItems { items.removeLast(items.count - Self.maxItems) }
    }

    func copy(_ text: String) {
        let pb = NSPasteboard.general
        pb.clearContents()
        pb.setString(text, forType: .string)
        lastChange = pb.changeCount
        remember(text)
    }

    func clear() {
        items.removeAll()
    }

    static func title(_ text: String) -> String {
        let oneLine = text.split(whereSeparator: { $0.isWhitespace }).joined(separator: " ")
        return oneLine.count > 50 ? String(oneLine.prefix(50)) + "…" : oneLine
    }

    // Глобальное сочетание ⌃⌥V: работает в любой программе без особых разрешений
    func registerHotKey() {
        var spec = EventTypeSpec(eventClass: OSType(kEventClassKeyboard), eventKind: UInt32(kEventHotKeyPressed))
        InstallEventHandler(GetApplicationEventTarget(), { _, _, _ in
            NotificationCenter.default.post(name: .murkaClipboardHotKey, object: nil)
            return noErr
        }, 1, &spec, nil, nil)
        let id = EventHotKeyID(signature: OSType(0x4D524B41), id: 1)
        RegisterEventHotKey(UInt32(kVK_ANSI_V), UInt32(controlKey | optionKey), id,
                            GetApplicationEventTarget(), 0, &hotKey)
    }
}
